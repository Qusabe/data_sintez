def parse_response(response):
    pattern = r"```sql\s*(.*?)\s*```"

    sql_blocks = re.findall(pattern, response, re.DOTALL)

    if sql_blocks:
        # Extract the last SQL query in the response text and remove extra whitespace characters
        last_sql = sql_blocks[-1].strip()
        return last_sql
    else:
        print("No SQL blocks found.")
        return ""


# [CHANGE 3] Remove the reasoning part from a raw model output.
# Depending on the chat template the opening <think> tag is either generated by the model
# or already part of the prompt, so only the closing </think> tag is relied upon.
def strip_thinking(text, thinking_enabled):
    if "</think>" in text:
        return text.rsplit("</think>", 1)[1].strip()
    if thinking_enabled:
        # reasoning never finished (hit the token limit) -> no usable answer
        return ""
    return text.strip()


# [CHANGE 4] Qwen's recommended sampling settings (thinking mode for precise/coding tasks;
# non-thinking mode otherwise). Used unless overridden on the command line.
def default_sampling(thinking):
    if thinking:
        return {"temperature": 0.6, "top_p": 0.95, "top_k": 20}
    return {"temperature": 0.7, "top_p": 0.8, "top_k": 20}


def load_model(model_name, use_4bit=True, cpu_offload=False, gpu_mem_gb=None, cpu_mem_gb=16):  # [CHANGE 8]
    """Load a Hugging Face causal LM and its tokenizer on the GPU."""
    if not torch.cuda.is_available():
        raise RuntimeError(
            "No GPU found. In Colab: Runtime -> Change runtime type -> T4 GPU, then reconnect."
        )

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"  # required for batched generation

    kwargs = {"device_map": "auto"}
    if use_4bit:
        kwargs["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.float16,
            # [CHANGE 8] allow modules that don't fit on the GPU to stay on the CPU (in fp32)
            llm_int8_enable_fp32_cpu_offload=cpu_offload,
        )
    else:
        kwargs["dtype"] = torch.float16  # T4 has no good bf16 support

    # [CHANGE 8] cap GPU usage so there is room left for activations / the KV cache;
    # everything that doesn't fit under the cap goes to CPU RAM
    if cpu_offload and gpu_mem_gb:
        kwargs["max_memory"] = {0: f"{gpu_mem_gb}GiB", "cpu": f"{cpu_mem_gb}GiB"}

    model = AutoModelForCausalLM.from_pretrained(model_name, **kwargs)
    model.eval()
    return model, tokenizer


def generate_responses(model, tokenizer, prompts, batch_size=1, max_new_tokens=1024,
                       max_prompt_tokens=None, thinking=False, greedy=False,
                       temperature=None, top_p=None):
    """
    Generate one response per prompt.

    - Prompts are sorted by length so each batch has little padding (less memory).
    - If a batch runs out of GPU memory, its prompts are retried one at a time.
    - A prompt that still doesn't fit is skipped (empty response, filtered out later).
    """
    # [CHANGE 2] chat format, [CHANGE 3] thinking switch passed to the chat template
    texts = [
        tokenizer.apply_chat_template(
            [{"role": "user", "content": p}],
            tokenize=False,
            add_generation_prompt=True,
            enable_thinking=thinking,
        )
        for p in prompts
    ]

    lengths = [len(tokenizer(t, add_special_tokens=False).input_ids) for t in texts]
    print(f"Prompt length in tokens: max={max(lengths)}, avg={sum(lengths) / len(lengths):.0f}")

    tok_kwargs = {}
    if max_prompt_tokens:
        tok_kwargs = {"truncation": True, "max_length": max_prompt_tokens}

    # [CHANGE 4] generation settings
    if greedy:
        gen_kwargs = {"do_sample": False}
    else:
        rec = default_sampling(thinking)
        gen_kwargs = {
            "do_sample": True,
            "temperature": temperature if temperature is not None else rec["temperature"],
            "top_p": top_p if top_p is not None else rec["top_p"],
            "top_k": rec["top_k"],
        }

    order = sorted(range(len(texts)), key=lambda i: lengths[i])
    responses = [None] * len(texts)

    def run(batch_idx):
        batch = [texts[i] for i in batch_idx]
        inputs = tokenizer(
            batch, return_tensors="pt", padding=True, add_special_tokens=False, **tok_kwargs
        ).to(model.device)

        with torch.no_grad():
            outputs = model.generate(
                **inputs,
                max_new_tokens=max_new_tokens,
                pad_token_id=tokenizer.pad_token_id,
                **gen_kwargs,
            )

        # Drop the prompt tokens and decode only what the model generated
        generated = outputs[:, inputs["input_ids"].shape[1]:]
        decoded = tokenizer.batch_decode(generated, skip_special_tokens=True)
        for i, r in zip(batch_idx, decoded):
            responses[i] = r

    for start in tqdm(range(0, len(order), batch_size), desc="Generating"):
        batch_idx = order[start:start + batch_size]
        try:
            run(batch_idx)
        except torch.OutOfMemoryError:
            torch.cuda.empty_cache()
            for i in batch_idx:  # retry one by one
                try:
                    run([i])
                except torch.OutOfMemoryError:
                    print(f"Skipping prompt {i} ({lengths[i]} tokens): too long for GPU memory")
                    responses[i] = ""
                    torch.cuda.empty_cache()
        torch.cuda.empty_cache()

    return responses


def llm_inference(model, prompts, db_ids, batch_size=1, max_new_tokens=1024, use_4bit=True,
                  cpu_offload=False, gpu_mem_gb=None, cpu_mem_gb=16,  # [CHANGE 8]
                  max_prompt_tokens=None, thinking=False, greedy=False,
                  temperature=None, top_p=None):
    """
    Generates responses using an LLM for given prompts.

    Args:
        model: Hugging Face model name or local path (e.g. Qwen/Qwen3.5-4B).
        prompts (list of str): A list of prompts for the model.
        db_ids (list of str): A list of database IDs corresponding to each prompt.

    Returns:
        list of dict: A list of dictionaries containing the prompt, db_id, and generated response.
    """

    # [CHANGE 1] load the model, then generate (replaces `responses = None`)
    llm, tokenizer = load_model(model, use_4bit=use_4bit, cpu_offload=cpu_offload,
                                gpu_mem_gb=gpu_mem_gb, cpu_mem_gb=cpu_mem_gb)  # [CHANGE 8]

    raw_responses = generate_responses(
        llm, tokenizer, prompts,
        batch_size=batch_size,
        max_new_tokens=max_new_tokens,
        max_prompt_tokens=max_prompt_tokens,
        thinking=thinking,
        greedy=greedy,
        temperature=temperature,
        top_p=top_p,
    )

    # [CHANGE 3] drop the reasoning part
    responses = [strip_thinking(r or "", thinking) for r in raw_responses]

    results = [
        {
            "prompt": prompt,
            "db_id": db_id,
            "response": response
        }
        for prompt, db_id, response in zip(prompts, db_ids, responses)
    ]

    return results


# [CHANGE 7] Keep only the prompts that belong to the first `num_dbs` distinct databases.
# The prompt file is written grouped by database (and the databases were chosen randomly
# by generate_sql_synthesis_prompts.py), so this selects `num_dbs` random databases.
def select_databases(dataset, num_dbs):
    if num_dbs is None:
        return dataset
    chosen = []
    for data in dataset:
        if data["db_id"] not in chosen:
            if len(chosen) >= num_dbs:
                continue
            chosen.append(data["db_id"])
    chosen = set(chosen)
    return [data for data in dataset if data["db_id"] in chosen]


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=str, default="Qwen/Qwen3.5-2B")  # [CHANGE 6] default added
    # [CHANGE 6] new options
    parser.add_argument("--batch_size", type=int, default=1)
    parser.add_argument("--max_new_tokens", type=int, default=4096,
                        help="Max generated tokens per prompt. Use e.g. 4096+ with --thinking.")
    parser.add_argument("--max_prompt_tokens", type=int, default=None,
                        help="Truncate prompts to this many tokens (cuts off the END of the prompt)")
    parser.add_argument("--thinking", action="store_true",
                        help="Enable Qwen3.5 thinking mode (slower, needs a larger --max_new_tokens).")
    parser.add_argument("--greedy", action="store_true",
                        help="Deterministic decoding instead of sampling.")
    parser.add_argument("--temperature", type=float, default=None,
                        help="Overrides the recommended temperature for the chosen mode.")
    parser.add_argument("--top_p", type=float, default=None)
    # [CHANGE 7] limit on the number of databases
    parser.add_argument("--num_dbs", type=int, default=None,
                        help="Use prompts from only the first N databases in the input file.")
    parser.add_argument("--limit", type=int, default=None,
                        help="Only process the first N prompts (quick test run)")
    parser.add_argument("--no_4bit", action="store_true", help="Load in fp16 instead of 4-bit")
    # [CHANGE 8] CPU offload options
    parser.add_argument("--cpu_offload", action="store_true",
                        help="Allow layers that don't fit in GPU memory to run on the CPU (very slow).")
    parser.add_argument("--gpu_mem_gb", type=float, default=None,
                        help="With --cpu_offload: max GPU memory to use, e.g. 2.5 on a 4 GB card.")
    parser.add_argument("--cpu_mem_gb", type=float, default=16,
                        help="With --cpu_offload: max CPU RAM to use.")
    parser.add_argument("--input", default="sql_synthesis/prompts/sql_synthesis_prompts.json")
    parser.add_argument("--output", default="sql_synthesis/results/sql_synthesis.json")

    opt = parser.parse_args()
    print(opt)

    with open(opt.input, encoding="utf-8") as f:
        input_dataset = json.load(f)
    input_dataset = select_databases(input_dataset, opt.num_dbs)  # [CHANGE 7]
    print(f"{len({d['db_id'] for d in input_dataset})} databases, {len(input_dataset)} prompts selected")
    if opt.limit:
        input_dataset = input_dataset[:opt.limit]
    output_file = opt.output

    db_ids = [data["db_id"] for data in input_dataset]
    prompts = [data["prompt"] for data in input_dataset]

    results = llm_inference(
        opt.model, prompts, db_ids,
        batch_size=opt.batch_size,
        max_new_tokens=opt.max_new_tokens,
        use_4bit=not opt.no_4bit,
        cpu_offload=opt.cpu_offload,  # [CHANGE 8]
        gpu_mem_gb=opt.gpu_mem_gb,
        cpu_mem_gb=opt.cpu_mem_gb,
        max_prompt_tokens=opt.max_prompt_tokens,
        thinking=opt.thinking,
        greedy=opt.greedy,
        temperature=opt.temperature,
        top_p=opt.top_p,
    )

    # [CHANGE 5] attach parsed SQL and metadata carried over from the prompt-generation step,
    # then keep only records where a SQL block was actually found
    final_results = []
    for result, data in zip(results, input_dataset):
        sql = parse_response(result["response"]) if result["response"] else ""
        if not sql:
            continue
        result["sql"] = sql
        result["statement_type"] = data.get("statement_type")
        result["complexity"] = data.get("complexity")
        final_results.append(result)

    print(f"Kept {len(final_results)}/{len(results)} responses with a SQL block")

    # [CHANGE 6] create the results folder if needed
    os.makedirs(os.path.dirname(os.path.abspath(output_file)), exist_ok=True)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(json.dumps(final_results, indent=2, ensure_ascii=False))
    print(f"Saved {len(final_results)} results to {output_file}")